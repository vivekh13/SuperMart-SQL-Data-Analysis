## Part A — Easy to Moderate (fundamentals)
-- 1. **SELECT / FROM** — Retrieve all columns for every customer in the `customers` table.
     SELECT * 
     FROM customers;
     

-- 2. **WHERE** — List all products that belong to the `Electronics` category.
select *
from products
where category = 'Electronics';

-- 3. **WHERE (comparison)** — Find all products priced above ₹2000.
select *
from products
where price > 2000;

-- 4. **WHERE (multiple conditions)** — Find all orders with `status = 'Delivered'` AND `region = 'West'`.
select * from orders
where status = 'Delivered' and region = 'West';

-- 5. **DISTINCT** — List all unique categories present in the `products` table.

select distinct category
from products;

-- 6. **DISTINCT** — List all unique states customers come from.
select distinct state
from customers ;

-- 7. **ORDER BY** — List all products sorted by price, highest to lowest.
select *
from products
order by price desc;

-- 8. **LIKE / wildcard** — Find all customers whose name starts with `'A'`.
select * 
from customers
where customer_name like 'A%';

-- 9. **BETWEEN / IN** — Find all orders placed in the `region` `'North'` or `'South'` using `IN`.
select *
from orders
where region in ('north','south');

-- 10. **Aggregate basics** — Count the total number of orders in the `orders` table.
select count(order_id) as total_order
from orders;

-- 11. **GROUP BY** — For each `category`, find the average product price.
select category, avg(price) as avg_product_price
from products
group by category;

-- 12. **GROUP BY + ORDER BY** — For each `region`, count how many orders were placed, sorted from most to fewest.
select region, count(status) as order_placed
from orders
group by region
order by order_placed desc;

-- 13. **HAVING** — Find categories that have more than 4 products listed.
select category, count(product_name) as product_listed
from products
group by category
having product_listed > 4;

-- 14. **HAVING** — Find regions where the total number of orders is greater than 10.
select region, count(order_id) as total_orders
from orders
group by region
having count(order_id) > 10;
